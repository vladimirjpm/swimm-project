namespace Swimm.Domain;

/// <summary>
/// Значения <c>Results.Round</c> — раунд зачёта, как его печатает источник
/// (И13, docs/data-integrity.md §10). null — источник раундов не различает, так у всех
/// PDF-протоколов.
///
/// Раунд — ФАКТ источника. Наш вывод «был ли это отбор» живёт отдельно, в
/// <c>Results.HeatType</c>: на нём висит правило Р34 «место в предварительном — не награда».
/// </summary>
public static class ResultRounds
{
    /// <summary>«גמר ישיר» — прямой финал: утренний зачёт возрастных групп со своими медалями.</summary>
    public const string TimedFinal = "timed-final";

    /// <summary>«גמר» — вечерний финал первенства в своей возрастной ступени.</summary>
    public const string Final = "final";

    /// <summary>«מוקדמות» — предварительные.</summary>
    public const string Prelim = "prelim";

    /// <summary>
    /// Финал БЕЗ возрастной категории — секция «כללי» («общий»), куда попадают пловцы,
    /// чья ступень отдельно не разыгрывается.
    ///
    /// Клубных очков и медалей НЕ приносит (правило Р43): у организатора зачётная единица —
    /// возрастная ступень, и «כללי» в его же таблице стоит с пустой колонкой «ניקוד קבוצתי».
    /// Свои очки эти пловцы получают в возрастной секции того же дня. Проверено на 1581:
    /// исключение «כללי» убрало 175 очков нашего перебора из 406.
    /// </summary>
    public const string FinalOpen = "final-open";
}
