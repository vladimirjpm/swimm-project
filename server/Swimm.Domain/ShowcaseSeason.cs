namespace Swimm.Domain;

/// <summary>
/// ВИТРИННЫЙ сезон — граница для рекордов, season best и KPI страницы клуба
/// (решение Влада 2026-08-09, docs/season-boundary-rule.md).
///
/// Сезон кончается ПОСЛЕДНИМ зимним чемпионатом — самым поздним из всех возрастных
/// ступеней (детский, юношеский, бугрим, мастерс): зимний чемпионат это финиш цикла,
/// а не его середина. Следующий день — начало нового витринного сезона.
///
/// ⚠ Это НЕ замена <see cref="SeasonMath"/>. Календарная граница (1 сен — 31 авг) остаётся
/// единственным источником правды для возраста в сезоне, фильтра сезонов, ростера и
/// импорта; витринная живёт отдельным понятием осознанно. Две границы в одном продукте —
/// тот же класс ошибок, что <c>StartYearOf</c> против <c>FederationYearOf</c>: обе законны,
/// ошибка — молча смешать их в одном месте.
///
/// Граница вычисляется ПО ДАННЫМ, поэтому:
///  • разная год от года и известна только постфактум;
///  • импорт зимнего чемпионата задним числом сдвигает её, и состав «этого сезона» меняется.
/// </summary>
public static class ShowcaseSeason
{
    /// <summary>
    /// Начало текущего витринного сезона — день ПОСЛЕ последнего прошедшего зимнего
    /// чемпионата. Зимних чемпионатов в данных нет (не импортированы, отменены) → падаем
    /// на календарную границу сезона: пустая витрина хуже приблизительной.
    /// </summary>
    public static DateTime StartOf(IEnumerable<DateTime> winterChampionshipDates, DateTime now)
    {
        DateTime? last = null;
        foreach (var d in winterChampionshipDates)
        {
            if (d > now) continue;                       // будущий чемпионат границы не двигает
            if (last is null || d > last) last = d;
        }

        return last is DateTime d0
            ? d0.Date.AddDays(1)
            : SeasonMath.StartOf(SeasonMath.StartYearOf(now));
    }
}
