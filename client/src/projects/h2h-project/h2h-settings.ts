/**
 * Кем занят ЛЕВЫЙ слот на пустой странице:
 *  • `empty` — оба слота пусты, страница нейтральна (умолчание);
 *  • `me`    — primary favorite залогиненного («это я»).
 *
 * ⚠ РЕШЕНИЕ ВЛАДА 03.09.2026: умолчание — `empty`. Автоподстановка «ME» мешала:
 * страница открывалась уже занятой, и убрать своего пловца крестиком было нельзя —
 * слот заполнялся заново. Пловец в слоте появляется только по ЯВНОМУ выбору: клик по
 * чипу избранного, поиск или `?h2h_a=` в адресе.
 *
 * Живёт ОДНОЙ константой, чтобы переключение стоило одну правку; когда появится экран
 * настроек — переедет туда, тип не изменится. При `me` подстановка одноразовая (см.
 * `autoLeftDoneRef` в `h2h-project.tsx`) — иначе она спорит с крестиком.
 */
export type H2HDefaultLeft = 'me' | 'empty';

export const H2H_DEFAULT_LEFT: H2HDefaultLeft = 'empty';
