/**
 * Кем занят ЛЕВЫЙ слот на пустой странице:
 *  • `me`    — primary favorite залогиненного («это я»), самый частый сценарий «я против X»;
 *  • `empty` — оба слота пусты, страница нейтральна.
 *
 * Живёт ОДНОЙ константой, чтобы переключение стоило одну правку; когда появится экран
 * настроек — переедет туда, тип не изменится.
 *
 * ⚠ `a` в адресе всегда сильнее: пришли по ссылке — открылось ровно то, что в ней.
 * И подстановка «ME» НЕ пишется в адрес, пока не выбран второй, — иначе ссылка на пустую
 * страницу превращалась бы в чужую личную.
 */
export type H2HDefaultLeft = 'me' | 'empty';

export const H2H_DEFAULT_LEFT: H2HDefaultLeft = 'me';
