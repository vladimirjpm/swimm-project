import React from 'react';
import type { TopbarActivePage } from '../app-topbar/app-topbar';

/**
 * Типы каркаса страницы сущности (`entity-page.tsx`).
 * План и обоснования — `docs/plans/entity-page-shell-plan.md` §3.
 */

/**
 * Состояние страницы считает САМА страница, а не каркас. Правило клуба, ради которого так:
 * плашка «Loading…» показывается только когда данных нет вовсе — при смене сезона данные
 * остаются на экране и обновляются на месте, иначе плашка вставляется над контентом и
 * страница прыгает вниз-вверх на каждый клик по фильтру.
 */
export type EntityPageStatus = 'loading' | 'ready' | 'notfound' | 'error';

/** Карточка панели таба. Порядок в массиве — порядок на экране. */
export interface EntityCardSpec {
  /** Стабильный ключ: по нему React различает карточки при перестановке. */
  id: string;
  /**
   * `half` — половина ширины начиная с 960px (соседние `half` встают парой),
   * `full` (по умолчанию) — во всю ширину панели и разрывает ряд.
   */
  span?: 'half' | 'full';
  /** Функция, а не готовый JSX: тело считается только у активного таба. */
  render: () => React.ReactNode;
}

/**
 * Навигация по табам, доступная карточкам панели. Нужна дайджесту: его карточки — витрины
 * соседних табов, и ссылка «All 20 records →» обязана уводить туда же, где карточка целиком.
 *
 * `go` не просто переключает таб, но и поднимает страницу к верху «папки»: после перехода из
 * середины длинного дайджеста человек иначе оказывается в середине чужой панели. Прокрутка
 * здесь `window.scrollTo`, а не `scrollIntoView` — второй у липкого топбара уводит заголовок
 * под полосу.
 */
export interface EntityTabNav<T extends string = string> {
  go: (id: T) => void;
}

/** Таб страницы. Набор собирается массивом с отсевом — «убрать таб» = не положить его. */
export interface EntityTabSpec<T extends string = string> {
  id: T;
  /** Глиф; декоративный — внутри DeepTabs он aria-hidden. */
  icon: string;
  label: string;
  /** Короткое имя для мобайла: колонка там узкая, длинное режется многоточием. */
  shortLabel?: string;
  /** Подпись-сводка под именем (только десктоп). ЖИВЫЕ данные, не хардкод. */
  sub?: string;
  /**
   * Таб виден, но содержимое не положено (медиа участников, тренировки непайщику).
   * Вместо карточек в панель идёт `lockNotice`. Не путать с «не класть таб вовсе»:
   * то, что человеку знать не надо (админский инбокс), из набора просто исключается.
   */
  locked?: boolean;
  lockNotice?: React.ReactNode;
  /**
   * Карточки панели. Функция, а не готовый JSX: тело считается только у активного таба.
   * `nav` нужен дайджесту — карточке-витрине, которая уводит на «свой» таб.
   */
  cards: (nav: EntityTabNav<T>) => EntityCardSpec[];
}

export interface DeepEntityPageProps<T extends string = string> {
  /** Подсветка пункта в топбаре. У клуба пункта нет — не передаём (так было и до каркаса). */
  topbarActive?: TopbarActivePage;
  status: EntityPageStatus;
  /** Тексты плашек; у каждой страницы свои формулировки. */
  messages?: { loading?: string; notfound?: string; error?: string };
  /** СЛОТ: вариант шапки. Каркас в неё не заглядывает. */
  hero: React.ReactNode;
  /** СЛОТ между шапкой и табами: карусель сезонов, предстоящие старты, что угодно. */
  beforeTabs?: React.ReactNode;
  /** Название набора табов для скринридера («Club sections»). */
  tabsAriaLabel: string;
  tabs: EntityTabSpec<T>[];
  /** Таб по умолчанию (он же «без ?tab= в адресе»). По умолчанию — первый в массиве. */
  defaultTabId?: T;
  /**
   * УПРАВЛЯЕМЫЙ режим: активный таб приходит снаружи. Нужен, когда страница сама гейтит по
   * табу загрузку данных (страница пловца не шлёт запросы H2H, пока таб не открыт) или
   * держит свои легаси-алиасы `?tab=` (`history` → season). Не задан — таб живёт в каркасе.
   *
   * ⚠ Адрес пишет каркас в ОБОИХ режимах — правило «таб по умолчанию без параметра,
   * replaceState (не push)» должно жить в одном месте. В управляемом режиме `onTabChange`
   * обязан только положить значение в своё состояние, но НЕ трогать `?tab=`.
   */
  activeTabId?: T;
  /** Если странице нужно знать активный таб. В управляемом режиме — обязателен. */
  onTabChange?: (id: T) => void;
  /**
   * Класс плашки состояния, если у страницы своя (у пловца `.deep-notice` — пунктирная
   * рамка). Не задан — оболочка `.deep-card`, как на странице клуба.
   */
  noticeClassName?: string;
}
