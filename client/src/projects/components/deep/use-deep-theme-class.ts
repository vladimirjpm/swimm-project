import { useMode } from '../../../hooks/useMode';

/**
 * Класс темы Deep под текущий режим страницы.
 *
 * Токены `--deep-*` объявлены НА КЛАССЕ (`.theme-deep` / `.theme-deep-light`), а не на
 * `:root`, поэтому их надо включить на своём контейнере — иначе весь принятый дизайн
 * (карточки, cyan-акценты, золото) рисуется пустыми переменными.
 *
 * Отдельный хук появился, когда таких контейнеров стало несколько: любой ПОРТАЛ (модалка
 * пикера, кнопка «наверх») рендерится в `body`, снаружи контейнера таба, и класс ему нужен
 * свой. Наступали на это дважды — кнопка выходила прозрачной, потому что `--deep-accent`
 * за пределами таба пустой.
 */
export function useDeepThemeClass(): string {
  const { mode } = useMode();
  return mode === 'dark' ? 'theme-deep' : 'theme-deep-light';
}
